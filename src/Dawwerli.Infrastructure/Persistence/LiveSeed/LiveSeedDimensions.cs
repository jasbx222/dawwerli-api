    /// <summary>
    /// The template a seeded product came from: names are "{template}", "{template} {variant}", "{template} مستعمل" or
    /// "{template} - {variant}". The longest matching template wins ("ثلاجة 14 قدم نوفروست" over "ثلاجة 14 قدم").
    /// </summary>
    public static LiveSeedData.ProductSeed? TemplateOf(LiveSeedData.CategoryKit kit, string productName)
    {
        LiveSeedData.ProductSeed? best = null;
        foreach (var t in kit.Products)
            if ((productName == t.Name || productName.StartsWith(t.Name + " ", StringComparison.Ordinal)) && (best is null || t.Name.Length > best.Name.Length))
                best = t;
        return best;
    }

    /// <summary>Size for a non-wall product (wall templates carry their own per-variant sizes).</summary>
    public static Size For(LiveSeedData.ProductSeed? template, string slug) =>
        template is not null && ByTemplate.TryGetValue(template.Name, out var s) ? s : ByCategory.TryGetValue(slug, out var c) ? c : S(30m, 20m, 10m);
